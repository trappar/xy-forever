    req = cmd['request']
    md.append('')
    if req.get('ignored'):
        md.append('Request: empty (the device ignores any payload).')
    elif not req['fields']:
        md.append('Request: empty.')
    else:
        md += field_table(req['fields'], 'Request field (%s)' % size_text(req['size']))   # 1.10: the size in the head
