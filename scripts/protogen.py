NOTICE = 'Generated by scripts/protogen.py from protocol/v1.json: do not edit.'


class SpecError(ValueError):
    pass


def _no_duplicate_keys(pairs):
    out = {}
    for key, value in pairs:
        if key in out:
            raise SpecError('duplicate key %r' % key)
        out[key] = value
    return out


def load(path=SPEC):
    return json.loads(Path(path).read_text(encoding='utf-8'), object_pairs_hook=_no_duplicate_keys)


# ---- schema -------------------------------------------------------------------------------

INT_BYTES = {'u8': 1, 'u16': 2, 'u32': 4}
FIELD_TYPE = re.compile(r'^(u8|u16|u32|bytes\[([1-9][0-9]*)\]|cstr|text|rest)$')
HEX_TYPE = re.compile(r'^0x[0-9a-f]{2}$')
NAME = re.compile(r'^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)?$')
SYMBOL = re.compile(r'^[a-z][a-z0-9_]*$')
SWITCH = re.compile(r'^XYF_[A-Z0-9_]+$')
VERSION = re.compile(r'^[0-9]+\.[0-9]+$')
HEX = re.compile(r'^([0-9a-f]{2})*$')
CLASSES = ('core', 'product', 'dev')
STATUS_CLASSES = ('ok', 'request', 'support', 'order', 'device', 'content', 'policy', 'job')
DIRECTIONS = ('request', 'reply', 'event')
ON_ERROR = ('status', 'full')
ENCODINGS = ('ascii', 'utf-8')
STREAM_DIRECTIONS = ('to_device', 'to_host')
TRANSPORT_FACTS = ('usb_vendor_id', 'usb_product_id', 'product_usb_ids', 'usb_product', 'interface_classes', 'stream', 'line_settings',
                   'control_lines', 'usb_serial_number', 'simulator_port')
RANGE_KINDS = ('dev', 'event', 'retired')
REQUIRED_CONSTANTS = ('header_bytes', 'trailer_bytes', 'max_payload', 'max_data', 'max_read', 'put_chunk',
                      'max_path', 'max_stage', 'max_log_text', 'max_hello')
from protogen_hello import (BUILD_MACROS, HELLO_SOURCES, RUNTIME_BYTES,  # noqa: E402
                            RUNTIME_SWITCHES, answered, hello_fixed, hello_source, render_cpp_hello)
HELLO_TEXT = re.compile(r'^[!-:<>-~]+$')          # printable ASCII without space, ';' and '='
# object kind -> (required keys, optional keys)
KEYS = {
    'top': ({'$comment', 'protocol', 'transport', 'frame', 'constants', 'rules', 'statuses', 'common_errors',
             'commands', 'events', 'hello', 'golden', 'streams', 'reserved'}, set()),
    'protocol': ({'name', 'version', 'intro'}, set()),
    'transport': ({'doc'} | set(TRANSPORT_FACTS), set()),
    'fact': ({'value', 'verified', 'doc'}, set()),
    'common_error': ({'status', 'except', 'doc'}, set()),
    'frame': ({'magic', 'reply_bit', 'crc', 'fields'}, set()),
    'frame_field': ({'name', 'type', 'doc'}, set()),
    'constant': ({'name', 'value', 'doc'}, set()),
    'rule': ({'name', 'text'}, set()),
    'status': ({'code', 'name', 'class', 'since', 'doc'}, set()),
    'command': ({'type', 'name', 'symbol', 'class', 'since', 'switch', 'summary', 'timeout_ms', 'destructive',
                 'request', 'reply', 'errors', 'doc'}, {'test_only', 'switch_optional'}),
    'request': ({'size', 'fields'}, {'ignored', 'optional_fields'}),
    'reply': ({'size', 'fields', 'on_error', 'extensible'}, {'optional_fields'}),
    'payload': ({'size', 'fields', 'extensible'}, {'optional_fields'}),
    'field': ({'name', 'type', 'doc'}, {'optional', 'range', 'values', 'min_bytes', 'max_bytes', 'encoding'}),
    'event': ({'type', 'name', 'symbol', 'since', 'summary', 'payload', 'doc'}, set()),
    'hello': ({'prefix', 'doc', 'keys'}, set()),
    'hello_key': ({'name', 'since', 'doc'}, {'value', 'constant', 'source', 'max_bytes'}),
    'golden': ({'name', 'message', 'direction', 'seq', 'fields', 'hex'}, {'status'}),
    'stream': ({'name', 'direction', 'chunks', 'frames', 'doc'}, set()),
    'stream_frame': ({'type', 'seq', 'payload'}, set()),
    'reserved': ({'doc', 'statuses', 'renames', 'types'}, set()),
    'reserved_status': ({'code', 'name', 'item', 'doc'}, set()),
    'rename': ({'status', 'from', 'to', 'item'}, set()),
    'reserved_types': ({'first', 'last', 'kind', 'item', 'doc'}, set()),
}


class Checker:
    def __init__(self):
        self.errors = []

    def fail(self, where, message):
        self.errors.append('%s: %s' % (where, message))

    def obj(self, value, kind, where):
        """True when value is an object with exactly the allowed keys of kind."""
        if not isinstance(value, dict):
            self.fail(where, 'must be an object')
            return False
        required, optional = KEYS[kind]
        for key in sorted(required - set(value)):
            self.fail(where, 'missing key %r' % key)
        for key in sorted(set(value) - required - optional):
            self.fail(where, 'unknown key %r' % key)
        return required <= set(value)

    def typed(self, value, kinds, where):
        if isinstance(value, bool) and bool not in kinds or not isinstance(value, kinds):
            self.fail(where, 'must be %s' % '/'.join(k.__name__ for k in kinds))
            return False
        return True

    def text(self, value, where, empty=False):
        if self.typed(value, (str,), where) and not empty and not value.strip():
            self.fail(where, 'must not be empty')

    def unique(self, values, where, what):
        seen = set()
        for v in values:
            if v in seen:
                self.fail(where, 'duplicate %s %r' % (what, v))
            seen.add(v)


def type_number(c, value, where):
    if not isinstance(value, str) or not HEX_TYPE.match(value):
        c.fail(where, 'type must be "0x" and two lowercase hex digits')
        return None
    return int(value, 16)


def check_field(c, f, where, last):
    """Validates one field; returns (min bytes, max bytes, optional) or None."""
    if not c.obj(f, 'field', where):
        return None
    if not isinstance(f['name'], str) or not SYMBOL.match(f['name']):
        c.fail(where, 'bad field name %r' % (f['name'],))
    c.text(f['doc'], where + '.doc', empty=True)
    m = FIELD_TYPE.match(f['type']) if isinstance(f['type'], str) else None
    if not m:
        c.fail(where, 'unknown field type %r' % (f['type'],))
        return None
    kind = 'bytes' if m.group(2) else f['type']
    optional = f.get('optional', False)
    if 'optional' in f and f['optional'] is not True:
        c.fail(where, 'optional must be true when present')
    if kind in ('cstr', 'text'):
        if f.get('encoding') not in ENCODINGS:
            c.fail(where, '%s needs encoding %s' % (kind, ' or '.join(ENCODINGS)))
    elif 'encoding' in f:
        c.fail(where, 'encoding is only for cstr/text')
    if kind in INT_BYTES:
        for key in ('min_bytes', 'max_bytes'):
            if key in f:
                c.fail(where, '%s is only for cstr/text/rest' % key)
        top = (1 << (8 * INT_BYTES[kind])) - 1
        lo, hi = 0, top
        if 'range' in f:
            r = f['range']
            if not (isinstance(r, list) and len(r) == 2 and all(isinstance(x, int) and not isinstance(x, bool)
                                                                 for x in r) and 0 <= r[0] <= r[1] <= top):
                c.fail(where, 'range must be [low, high] within the type')
            else:
                lo, hi = r
        if 'values' in f:
            if not isinstance(f['values'], dict) or not f['values']:
                c.fail(where, 'values must be a non-empty object')
            else:
                for key, meaning in f['values'].items():
                    if not key.isdigit() or not lo <= int(key) <= hi:
                        c.fail(where, 'value %r outside the field range' % key)
                    c.text(meaning, where + '.values')
        size = INT_BYTES[kind]
        return size, size, optional
    for key in ('range', 'values'):
        if key in f:
            c.fail(where, '%s is only for integer fields' % key)
    if kind == 'bytes':
        for key in ('min_bytes', 'max_bytes'):
            if key in f:
                c.fail(where, '%s is not allowed for bytes[N]' % key)
        size = int(m.group(2))
        return size, size, optional
    if 'max_bytes' not in f:
        c.fail(where, '%s needs max_bytes' % kind)
        return None
    low = f.get('min_bytes', 1 if kind == 'cstr' else 0)
    high = f['max_bytes']
    if not all(isinstance(x, int) and not isinstance(x, bool) for x in (low, high)) or not \
            (1 if kind == 'cstr' else 0) <= low <= high:
        c.fail(where, 'min_bytes/max_bytes out of order')
        return None
    if kind in ('text', 'rest'):
        if not last:
            c.fail(where, '%s must be the last field' % kind)
        if optional:
            c.fail(where, '%s cannot be optional' % kind)
    return low, high, optional


def check_layout(c, layout, kind, where, max_payload):
    """Validates a request/reply/payload layout; returns its field names or None."""
    if not c.obj(layout, kind, where):
        return None
    fields = layout['fields']
    if not isinstance(fields, list):
        c.fail(where, 'fields must be a list')
        return None
    low = high = 0
    seen_optional = False
    ok = True
    for i, f in enumerate(fields):
        r = check_field(c, f, '%s.fields[%d]' % (where, i), i == len(fields) - 1)
        if r is None:
            ok = False
            continue
        if seen_optional and not r[2]:
            c.fail(where, 'optional fields must come last')
        seen_optional = seen_optional or r[2]
        low += 0 if r[2] else r[0]
        high += r[1]
    names = [f.get('name') for f in fields if isinstance(f, dict)]
    c.unique(names, where, 'field name')
    if seen_optional != ('optional_fields' in layout):
        c.fail(where, 'optional_fields is required for, and only for, a layout with optional fields')
    elif seen_optional and layout['optional_fields'] != 'all_or_none':
        c.fail(where, 'optional_fields must be "all_or_none"')
    if 'extensible' in layout:
        tail = fields[-1].get('type') if fields and isinstance(fields[-1], dict) else None
        if not isinstance(layout['extensible'], bool):
            c.fail(where, 'extensible must be true or false')
        elif layout['extensible'] and tail in ('rest', 'text'):
            c.fail(where, 'a layout that ends in %s cannot be extensible' % tail)
    size = layout['size']
    if not (isinstance(size, list) and len(size) == 2 and all(isinstance(x, int) for x in size)):
        c.fail(where, 'size must be [min, max]')
    elif ok and size != [low, high]:
        c.fail(where, 'size %r does not add up: the fields give [%d, %d]' % (size, low, high))
    if layout.get('ignored'):
        if fields:
            c.fail(where, 'an ignored request has no fields')
    elif 'ignored' in layout:
        c.fail(where, 'ignored must be true when present')
    status = 4 if kind == 'reply' else 0
    if ok and high + status > max_payload:
        c.fail(where, 'largest payload %d is above max_payload %d' % (high + status, max_payload))
    if kind == 'reply':
        e = layout['on_error']
        if isinstance(e, list):
            for name in e:
                if name not in names:
                    c.fail(where, 'on_error names unknown field %r' % name)
        elif e not in ON_ERROR:
            c.fail(where, 'on_error must be "status", "full" or a list of field names')
    return names


def validate(spec):
    """Raises SpecError listing every problem."""
    c = Checker()
    if not c.obj(spec, 'top', 'spec'):
        raise SpecError('\n'.join(c.errors))
    p = spec['protocol']
    if c.obj(p, 'protocol', 'protocol'):
        c.text(p['name'], 'protocol.name')
        if not isinstance(p['version'], str) or not VERSION.match(p['version']):
            c.fail('protocol.version', 'must be MAJOR.MINOR')
        if not isinstance(p['intro'], list) or not p['intro']:
            c.fail('protocol.intro', 'must be a list of paragraphs')
        else:
            for i, para in enumerate(p['intro']):
                c.text(para, 'protocol.intro[%d]' % i)
    f = spec['frame']
    if c.obj(f, 'frame', 'frame'):
        if f['magic'] != 'XF':
            c.fail('frame.magic', 'must be "XF"')
        if f['reply_bit'] != '0x80':
            c.fail('frame.reply_bit', 'must be "0x80"')
        c.text(f['crc'], 'frame.crc')
        for i, ff in enumerate(f['fields'] if isinstance(f['fields'], list) else []):
            if c.obj(ff, 'frame_field', 'frame.fields[%d]' % i) and not FIELD_TYPE.match(str(ff['type'])):
                c.fail('frame.fields[%d]' % i, 'unknown type %r' % ff['type'])
    constants = {}
    for i, k in enumerate(spec['constants']):
        where = 'constants[%d]' % i
        if c.obj(k, 'constant', where):
            if not isinstance(k['name'], str) or not SYMBOL.match(k['name']):
                c.fail(where, 'bad name')
            if not isinstance(k['value'], int) or isinstance(k['value'], bool) or k['value'] < 0:
                c.fail(where, 'value must be a non-negative integer')
            c.text(k['doc'], where + '.doc')
            constants[k['name']] = k['value']
    c.unique([k.get('name') for k in spec['constants']], 'constants', 'name')
    for name in REQUIRED_CONSTANTS:
        if name not in constants:
            c.fail('constants', 'missing %r' % name)
    max_payload = constants.get('max_payload', 0)
    for i, r in enumerate(spec['rules']):
        if c.obj(r, 'rule', 'rules[%d]' % i):
            c.text(r['text'], 'rules[%d].text' % i)
    c.unique([r.get('name') for r in spec['rules']], 'rules', 'name')

    statuses = {}
    for i, s in enumerate(spec['statuses']):
        where = 'statuses[%d]' % i
        if c.obj(s, 'status', where):
            if not isinstance(s['code'], int) or s['code'] != i:
                c.fail(where, 'codes must run 0, 1, 2, ... in order (got %r)' % (s['code'],))
            if not isinstance(s['name'], str) or not SYMBOL.match(s['name']):
                c.fail(where, 'bad name')
            if s['class'] not in STATUS_CLASSES:
                c.fail(where, 'class must be one of %s' % ', '.join(STATUS_CLASSES))
            if not isinstance(s['since'], str) or not VERSION.match(s['since']):
                c.fail(where, 'since must be MAJOR.MINOR')
            c.text(s['doc'], where + '.doc')
            statuses[s['name']] = s['code']
    c.unique([s.get('name') for s in spec['statuses']], 'statuses', 'name')
    if statuses.get('ok') != 0:
        c.fail('statuses', 'code 0 must be ok')

    messages = {}             # name -> (kind, layouts)
    types = {}                # wire type -> name (commands, their replies, events)
    symbols = []
    for i, cmd in enumerate(spec['commands']):
        where = 'commands[%d]' % i
        if not c.obj(cmd, 'command', where):
            continue
        where = 'command %s' % cmd['name']
        t = type_number(c, cmd['type'], where)
        if t is not None:
            if not 0 < t < 0x80:
                c.fail(where, 'request types are 0x01..0x7f')
            for wire in (t, t | 0x80):
                if wire in types:
                    c.fail(where, 'type 0x%02x already used by %s' % (wire, types[wire]))
                types[wire] = cmd['name']
        if not isinstance(cmd['name'], str) or not NAME.match(cmd['name']):
            c.fail(where, 'bad name')
        if not isinstance(cmd['symbol'], str) or not SYMBOL.match(cmd['symbol']):
            c.fail(where, 'bad symbol')
        symbols.append(cmd['symbol'])
        if cmd['class'] not in CLASSES:
            c.fail(where, 'class must be one of %s' % ', '.join(CLASSES))
        if 'test_only' in cmd and (cmd['test_only'] is not True or cmd['class'] != 'dev'):
            c.fail(where, 'test_only must be true and only on dev commands')
        if not isinstance(cmd['since'], str) or not VERSION.match(cmd['since']):
            c.fail(where, 'since must be MAJOR.MINOR')
        if cmd['switch'] is not None and (not isinstance(cmd['switch'], str) or not SWITCH.match(cmd['switch'])):
            c.fail(where, 'switch must be null or XYF_...')
        if (cmd['switch'] is None) == ('switch_optional' in cmd):
            c.fail(where, 'switch_optional is required for, and only for, a command with a build switch')
        elif 'switch_optional' in cmd:
            c.typed(cmd['switch_optional'], (bool,), where + '.switch_optional')
        c.text(cmd['summary'], where + '.summary')
        c.text(cmd['doc'], where + '.doc', empty=True)
        if not isinstance(cmd['timeout_ms'], int) or isinstance(cmd['timeout_ms'], bool) or cmd['timeout_ms'] <= 0:
            c.fail(where, 'timeout_ms must be a positive integer')
        c.typed(cmd['destructive'], (bool,), where + '.destructive')
        check_layout(c, cmd['request'], 'request', where + '.request', max_payload)
        check_layout(c, cmd['reply'], 'reply', where + '.reply', max_payload)
        if not isinstance(cmd['errors'], list):
            c.fail(where, 'errors must be a list')
        else:
            for e in cmd['errors']:
                if e not in statuses or e == 'ok':
                    c.fail(where, 'error %r is not a failure status' % (e,))
            c.unique(cmd['errors'], where, 'error')
        messages[cmd['name']] = ('command', cmd)
    for i, ev in enumerate(spec['events']):
        where = 'events[%d]' % i
        if not c.obj(ev, 'event', where):
            continue
        where = 'event %s' % ev['name']
        t = type_number(c, ev['type'], where)
        if t is not None:
            if t < 0x80:
                c.fail(where, 'event types are 0x80 or above')
            elif t in types:
                c.fail(where, 'type 0x%02x already used by %s' % (t, types[t]))
            elif t & 0x7f in types:
                c.fail(where, 'type 0x%02x (enum value) already used by %s' % (t & 0x7f, types[t & 0x7f]))
            types[t] = ev['name']
        if not isinstance(ev['name'], str) or not NAME.match(ev['name']):
            c.fail(where, 'bad name')
        if not isinstance(ev['symbol'], str) or not SYMBOL.match(ev['symbol']):
            c.fail(where, 'bad symbol')
        symbols.append(ev['symbol'])
        if not isinstance(ev['since'], str) or not VERSION.match(ev['since']):
            c.fail(where, 'since must be MAJOR.MINOR')
        c.text(ev['summary'], where + '.summary')
        c.text(ev['doc'], where + '.doc', empty=True)
        check_layout(c, ev['payload'], 'payload', where + '.payload', max_payload)
        if ev['name'] in messages:
            c.fail(where, 'name already used by a command')
        messages[ev['name']] = ('event', ev)
    c.unique([cmd.get('name') for cmd in spec['commands']], 'commands', 'name')
    c.unique(symbols + ['reply'], 'commands/events', 'symbol')

    check_transport(c, spec['transport'])
    commands = {cmd.get('name') for cmd in spec['commands'] if isinstance(cmd, dict)}
    for i, e in enumerate(spec['common_errors']):
        where = 'common_errors[%d]' % i
        if not c.obj(e, 'common_error', where):
            continue
        if e['status'] not in statuses or e['status'] == 'ok':
            c.fail(where, '%r is not a failure status' % (e['status'],))
        if not isinstance(e['except'], list) or any(n not in commands for n in e['except']):
            c.fail(where, 'except must list commands')
        c.text(e['doc'], where + '.doc')
    c.unique([e.get('status') for e in spec['common_errors'] if isinstance(e, dict)], 'common_errors', 'status')
    check_hello(c, spec, constants, messages)
    check_streams(c, spec['streams'], max_payload)

    for i, g in enumerate(spec['golden']):
        where = 'golden[%d]' % i
        if not c.obj(g, 'golden', where):
            continue
        kind, message = messages.get(g['message'], (None, None))
        if not message:
            c.fail(where, 'unknown message %r' % (g['message'],))
            continue
        if g['direction'] not in DIRECTIONS or (g['direction'] == 'event') != (kind == 'event'):
            c.fail(where, 'direction does not fit a %s' % kind)
            continue
        if not isinstance(g['seq'], int) or not 0 <= g['seq'] <= 255 or (kind == 'event' and g['seq'] != 0):
            c.fail(where, 'seq must be 0..255 (0 for events)')
        if (g['direction'] == 'reply') != ('status' in g):
            c.fail(where, 'a reply, and only a reply, has a status')
        elif 'status' in g and g['status'] not in statuses:
            c.fail(where, 'unknown status %r' % (g['status'],))
        layout = message['payload' if kind == 'event' else g['direction']]
        names = [f['name'] for f in layout['fields']]
        if not isinstance(g['fields'], dict) or any(n not in names for n in g['fields']):
            c.fail(where, 'fields must name fields of the layout')
        if not isinstance(g['hex'], str) or not HEX.match(g['hex']) or len(g['hex']) < 24:
            c.fail(where, 'hex must be a whole frame in lowercase hex')
    c.unique([g.get('name') for g in spec['golden']], 'golden', 'name')

    r = spec['reserved']
    if c.obj(r, 'reserved', 'reserved'):
        c.text(r['doc'], 'reserved.doc')
        for i, s in enumerate(r['statuses']):
            where = 'reserved.statuses[%d]' % i
            if c.obj(s, 'reserved_status', where):
                if s['code'] in statuses.values() or s['name'] in statuses:
                    c.fail(where, 'reserved status %r collides with a defined one' % (s['name'],))
                if not isinstance(s['code'], int) or s['code'] < len(statuses):
                    c.fail(where, 'reserved codes follow the defined ones')
        c.unique([s.get('code') for s in r['statuses']], 'reserved.statuses', 'code')
        c.unique([s.get('name') for s in r['statuses']], 'reserved.statuses', 'name')
        by_code = {v: k for k, v in statuses.items()}
        for i, n in enumerate(r['renames']):
            where = 'reserved.renames[%d]' % i
            if c.obj(n, 'rename', where) and by_code.get(n['status']) != n['from']:
                c.fail(where, 'status %r is not named %r' % (n['status'], n['from']))
        ranges = []
        for i, t in enumerate(r['types']):
            where = 'reserved.types[%d]' % i
            if not c.obj(t, 'reserved_types', where):
                continue
            first, last = type_number(c, t['first'], where), type_number(c, t['last'], where)
            if first is None or last is None:
                continue
            if first > last:
                c.fail(where, 'first is above last')
            if t['kind'] not in RANGE_KINDS:
                c.fail(where, 'kind must be one of %s' % ', '.join(RANGE_KINDS))
            for other in ranges:
                if first <= other[1] and other[0] <= last:
                    c.fail(where, 'range overlaps 0x%02x..0x%02x' % other[:2])
            ranges.append((first, last, t['kind']))
        for first, last, kind in ranges:
            for cmd in spec['commands']:
                t = int(cmd['type'], 16) if HEX_TYPE.match(str(cmd.get('type'))) else -1
                if first <= t <= last and not (kind == 'dev' and cmd.get('class') == 'dev'):
                    c.fail('command %s' % cmd.get('name'), 'type lies in the reserved %s range' % kind)
        events = [rg for rg in ranges if rg[2] == 'event']
        for ev in spec['events']:
            t = int(ev['type'], 16) if HEX_TYPE.match(str(ev.get('type'))) else -1
            if events and not any(a <= t <= b for a, b, _ in events):
                c.fail('event %s' % ev.get('name'), 'type outside the event range')
    if c.errors:
        raise SpecError('\n'.join(c.errors))
    return spec


def check_transport(c, t):
    if not c.obj(t, 'transport', 'transport'):
        return
    c.text(t['doc'], 'transport.doc')
    for name in TRANSPORT_FACTS:
        fact, where = t[name], 'transport.' + name
        if c.obj(fact, 'fact', where):
            c.typed(fact['verified'], (bool,), where + '.verified')
            c.text(fact['doc'], where + '.doc')
    for name in ('usb_vendor_id', 'usb_product_id', 'simulator_port'):
        value = t[name].get('value') if isinstance(t[name], dict) else None
        if not isinstance(value, int) or isinstance(value, bool) or not 0 < value <= 0xffff:
            c.fail('transport.' + name, 'value must be a 16-bit number')
    ids = t['product_usb_ids'].get('value') if isinstance(t['product_usb_ids'], dict) else None
    if not (isinstance(ids, list) and len(ids) == 2 and
            all(isinstance(v, int) and not isinstance(v, bool) and 0 < v <= 0xffff for v in ids)):
        c.fail('transport.product_usb_ids', 'value must be [vendor id, product id], 16-bit numbers')


def check_streams(c, streams, max_payload):
    for i, st in enumerate(streams):
        where = 'streams[%d]' % i
        if not c.obj(st, 'stream', where):
            continue
        c.text(st['name'], where + '.name')
        c.text(st['doc'], where + '.doc')
        if st['direction'] not in STREAM_DIRECTIONS:
            c.fail(where, 'direction must be one of %s' % ', '.join(STREAM_DIRECTIONS))
        if not isinstance(st['chunks'], list) or not st['chunks'] or \
                not all(isinstance(h, str) and h and HEX.match(h) for h in st['chunks']):
            c.fail(where, 'chunks must be non-empty lowercase hex strings')
        if not isinstance(st['frames'], list):
            c.fail(where, 'frames must be a list')
            continue
        for j, fr in enumerate(st['frames']):
            fw = '%s.frames[%d]' % (where, j)
            if not c.obj(fr, 'stream_frame', fw):
                continue
            t = type_number(c, fr['type'], fw)
            if t is not None and (t < 0x80) != (st['direction'] == 'to_device'):
                c.fail(fw, 'requests go to the device, replies and events to the host')
            if not isinstance(fr['seq'], int) or isinstance(fr['seq'], bool) or not 0 <= fr['seq'] <= 255:
                c.fail(fw, 'seq must be 0..255')
            if not isinstance(fr['payload'], str) or not HEX.match(fr['payload']) or len(fr['payload']) > 2 * max_payload:
                c.fail(fw, 'payload must be lowercase hex of at most max_payload bytes')
    c.unique([st.get('name') for st in streams if isinstance(st, dict)], 'streams', 'name')


def check_hello(c, spec, constants, messages):
    """The hello keys: one value per key, each fits the text, the longest text fits max_hello."""
    h = spec['hello']
    if not c.obj(h, 'hello', 'hello'):
        return
    c.text(h['doc'], 'hello.doc')
    if not isinstance(h['prefix'], str) or not HELLO_TEXT.match(h['prefix']):
        c.fail('hello.prefix', 'must be printable ASCII without space, ";" and "="')
        return
    longest = len(h['prefix'])
    keys = h['keys'] if isinstance(h['keys'], list) else []
    for i, k in enumerate(keys):
        where = 'hello.keys[%d]' % i
        if not c.obj(k, 'hello_key', where):
            continue
        if not isinstance(k['name'], str) or not SYMBOL.match(k['name']):
            c.fail(where, 'bad name')
            continue
        if not isinstance(k['since'], str) or not VERSION.match(k['since']):
            c.fail(where, 'since must be MAJOR.MINOR')
        c.text(k['doc'], where + '.doc')
        given = [key for key in ('value', 'constant', 'source') if key in k]
        if len(given) != 1:
            c.fail(where, 'needs exactly one of value, constant, source')
            continue
        if ('max_bytes' in k) != (k.get('source') in BUILD_MACROS):
            c.fail(where, 'max_bytes is required for, and only for, the release and mode sources')
            continue
        if 'value' in k:
            value = k['value'] if isinstance(k['value'], str) and HELLO_TEXT.match(k['value']) else None
            if value is None:
                c.fail(where, 'value must be printable ASCII without space, ";" and "="')
                continue
            size = len(value)
        elif 'constant' in k:
            if k['constant'] not in constants:
                c.fail(where, 'unknown constant %r' % (k['constant'],))
                continue
            size = len(str(constants[k['constant']]))
        elif k['source'] not in HELLO_SOURCES:
            c.fail(where, 'source must be one of %s' % ', '.join(HELLO_SOURCES))
            continue
        elif k['source'] in BUILD_MACROS:
            if not isinstance(k['max_bytes'], int) or isinstance(k['max_bytes'], bool) or not 1 <= k['max_bytes'] <= 32:
                c.fail(where, 'max_bytes must be 1..32')
                continue
            size = k['max_bytes']
        else:
            size = dict(RUNTIME_BYTES, version=len(spec['protocol']['version']))[k['source']]
            if k['source'] == 'stage2' and k is not keys[-1]:
                c.fail(where, 'the stage2 key must be the last key (the device sets it at run time)')
        longest += 2 + len(k['name']) + size
    c.unique([k.get('name') for k in keys if isinstance(k, dict)], 'hello.keys', 'name')
    c.unique([k['source'] for k in keys if isinstance(k, dict) and 'source' in k], 'hello.keys', 'source')
    top = constants.get('max_hello', 0)
    if longest > top:
        c.fail('hello', 'the longest text (%d bytes) is above max_hello %d' % (longest, top))
    kind, cmd = messages.get('hello', (None, None))
    info = cmd['reply']['fields'][-1] if kind == 'command' and cmd['reply']['fields'] else {}
    if info.get('max_bytes') != top:
        c.fail('command hello', 'the reply text must be at most max_hello bytes')


