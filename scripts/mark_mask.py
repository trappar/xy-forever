"""The infinity mark's alpha masks (#315): target/ui_mark_logo.ipp (the logo's, included in ui_gfx.cpp) and
target/ui_mark_large.ipp (the screen saver's, in xyf_saver.hpp). A lemniscate of Bernoulli, stretched to its box,
stroked at an even width and anti-aliased: each pixel's alpha is its centre's distance to the curve against half the
stroke, in 16 levels. Usage: uv run scripts/mark_mask.py (writes both; tests/test_ui_mark.py checks they are
current)."""

import functools
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# name: (width, height, stroke) in pixels. The logo's: the old two rings' box, the letters' stroke.
MASKS = {'logo': (63, 35, 5), 'large': (96, 53, 7)}
POINTS = 2400  # samples along the curve: under 0.1 px apart at these sizes


def curve(width, height, stroke):
    """The centre line in pixel coordinates: the lemniscate fitted inside the box less half the stroke."""
    raw = []
    for i in range(POINTS):
        t = 2 * math.pi * i / POINTS
        d = 1 + math.sin(t) ** 2
        raw.append((math.cos(t) / d, math.sin(t) * math.cos(t) / d))
    xs, ys = [p[0] for p in raw], [p[1] for p in raw]
    sx = (width - stroke - 1) / (max(xs) - min(xs))
    sy = (height - stroke - 1) / (max(ys) - min(ys))
    return [((x - min(xs)) * sx + stroke / 2 + 0.5, (y - min(ys)) * sy + stroke / 2 + 0.5) for x, y in raw]


@functools.cache
def alpha(width, height, stroke):
    """Rows of 0..15: coverage of each pixel by the stroke (do not change the result: it is cached)."""
    near = [[math.inf] * width for _ in range(height)]
    reach = stroke // 2 + 2
    for px, py in curve(width, height, stroke):
        for j in range(max(0, int(py) - reach), min(height, int(py) + reach + 1)):
            for i in range(max(0, int(px) - reach), min(width, int(px) + reach + 1)):
                d = (i + 0.5 - px) ** 2 + (j + 0.5 - py) ** 2
                if d < near[j][i]:
                    near[j][i] = d
    return [[round(15 * max(0.0, min(1.0, stroke / 2 - math.sqrt(d) + 0.5))) for d in row] for row in near]


def source(name):
    width, height, stroke = MASKS[name]
    rows = alpha(width, height, stroke)
    data = [0x40 | a for row in rows for a in row]
    lines = [', '.join('0x%02x' % b for b in data[i : i + 16]) + ',' for i in range(0, len(data), 16)]
    return (
        '// Generated by scripts/mark_mask.py (uv run scripts/mark_mask.py): do not edit.\n'
        '// The infinity mark, %d x %d px, stroke %d: a byte a pixel, 0x40 | alpha (0..15), rows top to bottom\n'
        '// (ui_gfx.hpp Mask). Included in place.\n'
        '// clang-format off\n'
        'static const uint8_t mark_%s_alpha[%d] = {\n    %s\n};\n'
        '// clang-format on\n' % (width, height, stroke, name, len(data), '\n    '.join(lines))
    )


def path(name):
    return ROOT / 'target' / ('ui_mark_%s.ipp' % name)


def main():
    for name in MASKS:
        path(name).write_text(source(name))
        print(path(name))


if __name__ == '__main__':
    main()
