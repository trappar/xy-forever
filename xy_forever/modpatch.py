"""Mod assembly on the host, end to end (docs/storage/mods-assembly.md;
docs/STORAGE.md).

Runs the device's freestanding linker, patch and content steps (native/mod_link, mod_patch,
mod_content), compiled for the Mac with host/mod_assemble.cpp, on mod packages (xy_forever/modkit.py):
packages + stock os.ldr + official catalog -> native link -> native patch -> native content, with no
core.mjs on the native side.

    python3 -m xy_forever.modkit prove-patch GENERATION_DIR --sdk OPEN_XY [--sdk-commit C]
                                 --catalog op1_factory.json --stock os.ldr [--scratch DIR] [--keep DIR]
                                 [--official content.sha256]
    python3 -m xy_forever.modkit known-base BASE_DIR... [--stock os.ldr] [--catalog JSON] [--write]

prove-patch assembles each selection of modkit's prove natively and with open-xy's core.mjs (linkKit,
patchFirmware in website mode, buildAssets) on the kit rebuilt from the same packages: the os.ldr,
every content file and the link's numbers must be identical, the content list (files.sha256) must
name exactly buildAssets's files, the patch must pass its own checks including the cold LDR policy
(ldr::inspect with target/cold.cpp's ranges) and start_verify must accept the image read back from
disk; a selection core.mjs refuses must be refused alike by the native linker. The adapter runs the
steps as the device job will: whole files in RAM, each checked against its
files.sha256, stock in the image buffer, the module linked straight into it at stock_bytes. Every
fact comes from the package files (the base's manifest and identities.txt included); the job names
only the selection and the files. Host only: no device, no network. Outputs go under the private root.
The real base must be in native/mod_known_bases.inc ("base": "known"); known-base regenerates that table
from official base folders (a new open-xy release). --official is the firmware's content.sha256.
"""

import hashlib
import json
import os
import shutil
import subprocess
import tempfile
import zlib
from pathlib import Path

from . import modkit as M
from . import modlink as L
from . import package_records

ROOT = Path(__file__).resolve().parents[1]
CXX = '/usr/bin/clang++'
NATIVE = ('mod_link', 'mod_elf', 'mod_numbers', 'mod_patch', 'mod_content', 'mod_job', 'hash', 'ldr', 'inflate', 'json')
PRODUCT_STACK_END = '0x8ab84000u'  # as xy_forever/tfw_extract.py: the product's module + stack
SLOTS = ('engine', 'effect', 'player')
KNOWN_BASES = ROOT / 'native/mod_known_bases.inc'
KNOWN_NUMBERS = (
    'stock_bytes',
    'stock_records',
    'module_base',
    'reserved_bytes',
    'module_bytes',
    'heap_fill_base',
    'heap_fill_bytes',
    'expanded_module_base',
)  # the last: 0 when the base offers no 4 MiB layout
MEMORY_MODES = ('standard', 'expanded')


def info_values(path):
    return package_records.read_values(Path(path).parent)


def known_base_entry(base, stock=None, catalog=None):
    """One mod_known_bases.inc entry from an official base package folder; stock/catalog, when given,
    must be the files the base pins."""
    base = Path(base)
    info = info_values(base / 'info.txt')
    edits = (base / 'edits.bin').read_bytes()
    listed = dict(reversed(l.split('  ', 1)) for l in (base / 'files.sha256').read_text().splitlines())
    M.check(listed.get('edits.bin') == hashlib.sha256(edits).hexdigest(), 'edits.bin differs from files.sha256')
    for path, key in ((stock, 'needs_os'), (catalog, 'catalog_sha256')):
        M.check(path is None or hashlib.sha256(Path(path).read_bytes()).hexdigest() == info[key], key + ' differs')

    def digest(text):
        return '{%s}' % ', '.join('0x' + text[i : i + 2] for i in range(0, 64, 2))

    numbers = ', '.join('0x%xu' % int(info.get(k, '0'), 0) for k in KNOWN_NUMBERS)
    return '// %s %s\n{%s,\n %s,\n {%s},\n %s},\n' % (
        info['profile'],
        info['generation'],
        digest(info['needs_os']),
        digest(info['catalog_sha256']),
        numbers,
        digest(listed['edits.bin']),
    )


def known_bases_text(bases, stock=None, catalog=None):
    """native/mod_known_bases.inc for the official base folders given (modkit known-base)."""
    return (
        '// Generated by `python3 -m xy_forever.modkit known-base BASE... --write` (mod_patch.cpp KnownBase).\n'
        + ''.join(known_base_entry(b, stock, catalog) for b in bases)
    )


SANITIZE = ('-O1', '-g', '-fsanitize=address,undefined', '-fno-omit-frame-pointer', '-fno-sanitize-recover=all')


def build(directory, flags=('-O2',), run=subprocess.run):
    """Compile the host adapter into directory; returns its path (run: hostbuild.run caches). XYF_SANITIZE=1
    in the environment makes every build the ASan/UBSan one (SANITIZE)."""
    if os.environ.get('XYF_SANITIZE'):
        flags = SANITIZE
    from .sim import policy_source  # cold.cpp's allowed and protected ranges, verbatim

    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / 'cold_policy.inc').write_text(policy_source())
    binary = directory / 'mod_assemble'
    command = [
        CXX,
        '-std=c++11',
        *flags,
        '-Wall',
        '-Wextra',
        '-Werror',
        '-DXYF_STACK_END=' + PRODUCT_STACK_END,
        '-I',
        str(directory),
        str(ROOT / 'host/mod_assemble.cpp'),
        *[str(ROOT / 'native' / (n + '.cpp')) for n in NATIVE],
        *[str(ROOT / 'target' / (n + '.cpp')) for n in ('xyf_manifest', 'xyf_package_record')],
        '-o',
        str(binary),
    ]
    result = run(command, capture_output=True, text=True)
    M.check(result.returncode == 0, 'host adapter build failed:\n' + (result.stderr or '')[-2000:])
    return binary


def job_text(
    generation_dir,
    machines,
    extensions,
    stock,
    catalog,
    profiling=False,
    limits=None,
    layout=None,
    official=None,
    unverified=False,
    name=None,
    memory='standard',
):
    """The adapter's job: the selection, the layout, the stock, catalog and official content list paths
    (official: default_official), unverified (the user confirmed a base that is not known), limits, the
    stepped job's manifest name (None: ENTRY_NAME), memory (MEMORY_MODES; expanded: the 4 MiB option)."""
    M.check(memory in MEMORY_MODES, 'unknown memory mode %r' % memory)
    root = Path(generation_dir).resolve()
    lines = ['generation %s' % root] + ['machine %s' % m for m in machines] + ['extension %s' % e for e in extensions]
    for mid, ident in (layout or {}).items():
        slot = next(i for i, s in enumerate(SLOTS) if s in ident)
        lines.append('layout %s %d %d %d' % (mid, slot, ident[SLOTS[slot]], ident['page']))
    lines += [
        'stock %s' % Path(stock).resolve(),
        'catalog %s' % Path(catalog).resolve(),
        'official %s' % Path(official or default_official(root)).resolve(),
        'profiling %d' % bool(profiling),
        'unverified %d' % bool(unverified),
    ]
    for what, value in (limits or {}).items():
        lines.append('limit %s %d' % (what, value))
    if name is not None:
        lines.append('name %s' % name)
    if memory != 'standard':
        lines.append('memory %s' % memory)
    return '\n'.join(lines) + '\n'


ENTRY_NAME = 'OP-XY mods'  # host/mod_assemble.cpp's default manifest name for the stepped job


def entry_files(generation_dir, assembled, machines, name=ENTRY_NAME):
    """The whole library entry the device job (native/mod_job) writes, from the one-shot assembly's
    {path: bytes} (run: os.ldr, content/..., files.sha256 of the content):
    the content and os.ldr unchanged, manifest.json (an assembled mod set,
    docs/STORAGE.md) and files.sha256 over every other file."""
    root = Path(generation_dir)
    base = info_values(root / 'base/info.txt')
    files = {p: b for p, b in assembled.items() if p != 'files.sha256'}
    ldr = files['os.ldr']
    files[package_records.NATIVE] = package_records.document(
        dict(
            type='firmware',
            name=name,
            kind='open-xy',
            bytes=len(ldr),
            crc32='%08x' % (zlib.crc32(ldr) & 0xFFFFFFFF),
            sha256=M.sha256(ldr),
            needs_os=base['needs_os'],
            generation=base['generation'],
            profile=base['profile'],
            machines=len(machines),
        )
    )
    files['files.sha256'] = list_text(files).encode()
    return files


def default_official(generation_dir):
    """The private content-manifests/<version>/content.sha256 for the base's profile (opxy-<version>)."""
    from . import paths

    profile = info_values(Path(generation_dir) / 'base/info.txt').get('profile', '')
    return paths.XYF / 'content-manifests' / profile.split('-', 1)[-1] / 'content.sha256'


def run(binary, job_path, out):
    result = subprocess.run([str(binary), 'run', str(job_path), str(out)], capture_output=True, text=True)
    M.check(result.returncode == 0, 'mod_assemble failed: ' + (result.stderr or result.stdout)[-2000:])
    report = json.loads(result.stdout)
    if 'link' in report:
        report['link_status'] = L.statuses()[report['link']] if report['link'] >= 0 else 'skipped'
        report['link_detail'] = bytes.fromhex(report['link_detail_hex']).decode('utf-8', 'replace')
        report['numbers'] = {mid: {slot: n, 'page': page} for mid, slot, n, page in report['numbers']}
    return report


def tree(folder):
    """{relative path: bytes} of every file under folder."""
    folder = Path(folder)
    return {p.relative_to(folder).as_posix(): p.read_bytes() for p in folder.rglob('*') if p.is_file()}


def list_text(files):
    """files.sha256 (010 form) for {path: bytes}."""
    return ''.join('%s  %s\n' % (M.sha256(files[p]), p) for p in sorted(files, key=str.encode))


MEMORY = (
    'link_scratch',
    'patch_scratch',
    'patch_state',
    'content_scratch',
    'content_state',
    'image_bytes',
    'catalog_limit',
    'list_limit',
)


def compare(core_dir, link_dir, native_dir, report):
    """Row facts: the native outputs against core.mjs's."""
    native = tree(native_dir)
    core_files = tree(core_dir)
    ldr = native.pop('os.ldr', None)
    listed = native.pop('files.sha256', None)
    link = json.loads((Path(link_dir) / 'link.json').read_text())
    memory = {k: report[k] for k in MEMORY}
    return dict(
        ldr_identical=ldr is not None and ldr == (Path(link_dir) / 'os.ldr').read_bytes(),
        content_identical=native == core_files,
        files=len(core_files),
        list_matches=listed is not None and listed.decode() == list_text(core_files),
        numbers_identical=report['numbers'] == link['numbers'],
        link=report['link_status'],
        link_detail=report['link_detail'],
        patch=report['patch'],
        base=report['base'],
        verify=report['verify'],
        content=report['content'],
        copy=report['copy'],
        input=report['input'],
        bytes=report['bytes'],
        entry=report['entry'],
        initialized=report['initialized'],
        allocated=link['sizes']['allocated'],
        available=link['sizes']['available'],
        memory=dict(memory, total=sum(memory.values()), largest_file=report['largest_file']),
        steps=dict(
            link=report['link_steps'],
            zero=report['zero_steps'],
            patch=report['patch_steps'],
            content=report['content_steps'],
        ),
        longest_step_ms=max(
            report['link_longest_ms'],
            report['patch_longest_ms'],
            report['verify_longest_ms'],
            report['content_longest_ms'],
        ),
    )


def prove(
    generation_dir,
    sdk,
    catalog_path,
    stock,
    scratch=None,
    sdk_commit=None,
    selections=None,
    keep=None,
    binary=None,
    official=None,
    memory='standard',
):
    """core.mjs (link, patch, assets) against the native end-to-end assembly, per selection; memory 'expanded':
    both with the 4 MiB option (core.mjs memoryKit(kit, true), the website's checkbox; the job's memory line)."""
    M.check(memory in MEMORY_MODES, 'unknown memory mode %r' % memory)
    root = Path(generation_dir)
    catalog = Path(catalog_path).read_bytes()
    first = M.read_table((root / 'base/machines.txt').read_bytes())[0][1]
    if selections is None:
        kit = M.rebuild_kit(root, [first], [], catalog)
        selections = M.selections_for(kit, root)
    rows = []
    if scratch is None:
        from . import paths

        scratch = paths.SESSIONS / 'lane-mods'
        scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=scratch, prefix='prove-patch-') as tmp:
        tmp = Path(tmp)
        binary = binary or build(tmp / 'bin', run=_cached())
        jobs, names = [], {}
        for n, (name, machines, exts) in enumerate(selections):
            work = tmp / ('s%02d' % n)
            work.mkdir()
            names[name] = work
            (work / 'kit.json').write_text(json.dumps(M.rebuild_kit(root, machines, exts, catalog)))
            jobs.append(
                dict(
                    name=name,
                    kit=str(work / 'kit.json'),
                    machines=machines,
                    extensions=exts,
                    stock=str(stock),
                    link_out=str(work / 'link'),
                    write=str(work / 'core'),
                    expanded=memory == 'expanded',
                )
            )
        results = {r['name']: r for r in M.run_driver(M.sdk_tree(sdk, sdk_commit, tmp), jobs, tmp)}
        for name, machines, exts in selections:
            work, r = names[name], results[name]
            row = dict(selection=name, machines=len(machines), extensions=exts, error=r.get('error'))
            (work / 'native').mkdir()
            (work / 'job.txt').write_text(
                job_text(root, machines, exts, stock, catalog_path, official=official, memory=memory)
            )
            report = run(binary, work / 'job.txt', work / 'native')
            if row['error']:
                row.update(
                    link=report['link_status'],
                    link_detail=report['link_detail'],
                    input=report['input'],
                    refused_alike=report['link_status'] not in ('ok', 'skipped')
                    and L.same_refusal(report['link_status'], report['link_detail'], row['error']),
                    left_files=sorted(tree(work / 'native')),
                )
            else:
                row.update(compare(work / 'core', work / 'link', work / 'native', report))
            rows.append(row)
        if keep:
            shutil.copytree(tmp, keep, ignore=shutil.ignore_patterns('kit.json', 'open-xy'))
    return rows


def proven(row):
    if row.get('error'):
        return bool(row.get('refused_alike')) and not row.get('left_files')
    return (
        row['ldr_identical']
        and row['content_identical']
        and row['list_matches']
        and row['numbers_identical']
        and row['base'] == 'known'
        and (row['input'], row['link'], row['patch'], row['verify'], row['content'], row['copy'])
        == ('ok', 'ok', 'ok', 'ok', 'ok', 'ok')
    )


def _cached():
    from . import hostbuild

    return hostbuild.run
