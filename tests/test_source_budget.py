"""Source file budget: no hand-written source file over CAP bytes.

A file over the cap today is listed in OVER with its size: it may not grow, and once it is under the cap (or gone)
its entry fails the test until it is removed, so the list only shrinks. To grow a listed file, first split out the
part you touch (target/usb_service.cpp and its .ipp parts show the way). Generated files and tests are not counted.
"""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CAP = 32768                          # bytes

# (folder, suffixes, recursive)
TREES = (
    ('target', ('.cpp', '.hpp', '.ipp', '.inc'), True),
    ('native', ('.cpp', '.hpp', '.ipp', '.inc'), True),
    ('host', ('.cpp', '.hpp', '.ipp', '.inc'), True),
    ('sim', ('.cpp', '.hpp', '.ipp', '.inc'), True),
    ('xy_forever', ('.py',), True),
    ('scripts', ('.py',), True),
    ('.', ('.py',), False),
    ('clients/ts/src', ('.ts',), True),
    ('web/src', ('.ts',), True),
)
GENERATED = re.compile(r'generated by|do not edit', re.I)       # in a file's first lines
TEST = re.compile(r'(^test_.*\.py|_test\.(cpp|hpp)|\.(test|spec)\.ts)$')

# Over the cap today (bytes): may not grow; remove an entry once its file is under the cap.
OVER = {
    'clients/ts/src/client.ts': 33693,
    'host/mod_assemble.cpp': 55310,
    'native/mod_content.cpp': 33307,
    'native/mod_job.cpp': 47043,
    'native/mod_link.cpp': 65785,
    'native/mtp_responder.cpp': 33255,
    'scripts/device_pass.py': 128359,
    'scripts/protogen.py': 90178,
    'scripts/setup.py': 38062,
    'sim/runtime.cpp': 36479,
    'sim/stock.cpp': 40937,
    'target/cold_storage.cpp': 33710,
    'target/file_boot.cpp': 73184,
    'target/peer_services.cpp': 41949,
    'target/storage_server.cpp': 43048,
    'target/xyf_content_job.hpp': 34146,
    'xy_forever/conformance.py': 63763,
    'xy_forever/modkit.py': 64034,
    'xyf_build.py': 83047,
    'xyf_host.py': 51555,
}


def sources():
    """Every counted source file: {path relative to the repository: bytes}."""
    found = {}
    for folder, suffixes, recursive in TREES:
        base = ROOT / folder
        for path in (base.rglob('*') if recursive else base.glob('*')):
            if not path.is_file() or path.suffix not in suffixes or TEST.search(path.name):
                continue
            if 'node_modules' in path.parts:
                continue
            with path.open('rb') as f:
                head = f.read(400).decode('utf-8', 'replace')
            if GENERATED.search(head):
                continue
            found[path.relative_to(ROOT).as_posix()] = path.stat().st_size
    return found


class SourceBudgetTest(unittest.TestCase):
    def test_no_new_file_over_the_cap(self):
        over = {name: size for name, size in sources().items() if size > CAP and name not in OVER}
        self.assertEqual(over, {}, f'over {CAP} bytes: split the file (the part you touch) before it grows')

    def test_listed_files_do_not_grow(self):
        found = sources()
        for name, size in sorted(OVER.items()):
            with self.subTest(file=name):
                self.assertIn(name, found, f'{name} is gone or not counted: remove it from OVER')
                self.assertLessEqual(found[name], size, f'{name} grew: split out the part you touch first')
                self.assertGreater(found[name], CAP, f'{name} is under the cap now: remove it from OVER')

    def test_generated_and_tests_are_left_out(self):
        found = sources()
        for name in ('clients/ts/src/v1.ts', 'target/usb_proto_ids.hpp', 'native/mod_known_bases.inc',
                     'target/mtp_usb_test.cpp'):
            self.assertTrue((ROOT / name).is_file(), name)
            self.assertNotIn(name, found)
        self.assertIn('target/usb_service.cpp', found)


if __name__ == '__main__':
    unittest.main()
